import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'apps', 'web', 'public', 'third-party-notices.txt');
const LICENCE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

function packageDir(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (!dir.endsWith('/node_modules') && existsSync(join(candidate, 'package.json'))) {
      return realpathSync(candidate);
    }
    if (dirname(dir) === dir) break;
  }
  try {
    return dirname(createRequire(join(from, 'x.js')).resolve(`${name}/package.json`));
  } catch {
    return null;
  }
}

const seen = new Map();
function walk(name, from) {
  const dir = packageDir(name, from);
  if (!dir || seen.has(dir)) return;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir).filter((file) => LICENCE.test(file));
  seen.set(dir, {
    name: pkg.name ?? name,
    version: pkg.version ?? '',
    declared: typeof pkg.license === 'string' ? pkg.license : '',
    text: files.map((file) => readFileSync(join(dir, file), 'utf8').trim()).join('\n\n'),
  });
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, dir);
}

for (const app of ['apps/web', 'apps/server', 'packages/shared']) {
  const dir = join(ROOT, app);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  for (const dep of Object.keys(pkg.dependencies ?? {})) {
    if (!dep.startsWith('@hostile/')) walk(dep, dir);
  }
}
const electron = packageDir('electron', join(ROOT, 'apps', 'desktop'));
if (electron) walk('electron', join(ROOT, 'apps', 'desktop'));

const parts = [
  'Third-party notices for Hostile.\nGenerated by scripts/third-party-notices.mjs from the installed packages.\n',
];
const kept = join(ROOT, 'docs', 'third-party-licences');
for (const file of existsSync(kept) ? readdirSync(kept).sort() : []) {
  parts.push(`=== ${file} ===\n\n${readFileSync(join(kept, file), 'utf8').trim()}\n`);
}
const missing = [];
for (const entry of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.text)
    missing.push(`${entry.name} ${entry.version} (declares: ${entry.declared || 'nothing'})`);
  else parts.push(`=== ${entry.name} ${entry.version} ===\n\n${entry.text}\n`);
}
const repoLicence = readFileSync(join(ROOT, 'LICENSE'), 'utf8');
parts.push(
  `=== LiveKit server (livekit-server) ===\n\nLiveKit is licensed under the Apache License, Version 2.0. Its own NOTICE is livekit-notice.txt, near the top of this file, and its licence is the Apache 2.0 text below.\n\n${repoLicence.trim()}\n`,
);
if (missing.length) {
  parts.push(`=== Packages with no licence file to quote ===\n\n${missing.join('\n')}\n`);
}
writeFileSync(OUT, parts.join('\n'));
console.log(`${seen.size} packages, ${missing.length} with no licence file. Wrote ${OUT}`);
if (missing.length) console.log(missing.join('\n'));
