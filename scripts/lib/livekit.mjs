import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LOCAL_DIR, TOOLS_DIR } from './env.mjs';
import { runSync, which } from './proc.mjs';

export const LIVEKIT_VERSION = '1.13.7';

const exe = process.platform === 'win32' ? 'livekit-server.exe' : 'livekit-server';

export function projectLocalBinary() {
  return join(TOOLS_DIR, 'livekit', LIVEKIT_VERSION, exe);
}

export function findLivekitBinary(env) {
  const candidates = [];
  if (env.LIVEKIT_BIN) candidates.push({ path: env.LIVEKIT_BIN, source: 'LIVEKIT_BIN' });
  candidates.push({ path: projectLocalBinary(), source: '.tools (pnpm livekit:install)' });
  const onPath = which('livekit-server');
  if (onPath) candidates.push({ path: onPath, source: 'PATH' });
  for (const c of candidates) {
    if (existsSync(c.path)) {
      const v = runSync(c.path, ['--version']);
      const version = /(\d+\.\d+\.\d+)/.exec(v.stdout + v.stderr)?.[1] ?? null;
      return { ...c, version, missing: false };
    }
    if (c.source === 'LIVEKIT_BIN') return { ...c, version: null, missing: true };
  }
  return null;
}

export function renderDevLivekitConfig(env, { apiPort = env.API_PORT } = {}) {
  const nodeIp = env.LIVEKIT_NODE_IP || '127.0.0.1';
  const lines = [
    '# GENERATED by scripts/dev.mjs from .env - edits are overwritten on the next start.',
    '# Development-only LiveKit configuration.',
    `port: ${env.LIVEKIT_PORT}`,
    'bind_addresses:',
    '  - "127.0.0.1"',
    'rtc:',
    `  udp_port: ${env.LIVEKIT_RTC_UDP_PORT}`,
    '  use_external_ip: false',
    `  node_ip: "${nodeIp}"`,
    '  tcp_port: 0',
    '  enable_loopback_candidate: true',
    '  ips:',
    '    includes:',
    '      - 127.0.0.1/32',
    'keys:',
    `  ${env.LIVEKIT_API_KEY}: ${env.LIVEKIT_API_SECRET}`,
    'webhook:',
    `  api_key: ${env.LIVEKIT_API_KEY}`,
    '  urls:',
    `    - "http://127.0.0.1:${apiPort}/api/livekit/webhook"`,
    'room:',
    '  auto_create: true',
    '  empty_timeout: 60',
    '  departure_timeout: 10',
    'logging:',
    `  level: ${env.LIVEKIT_LOG_LEVEL || 'info'}`,
    'turn:',
    '  enabled: false',
    '',
  ];
  return lines.join('\n');
}

export function writeDevLivekitConfig(env) {
  mkdirSync(LOCAL_DIR, { recursive: true });
  const file = join(LOCAL_DIR, 'livekit.dev.yaml');
  writeFileSync(file, renderDevLivekitConfig(env), { mode: 0o600 });
  return file;
}
