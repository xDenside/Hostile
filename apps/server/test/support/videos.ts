export function buildFtyp(brand: string): Buffer {
  const box = Buffer.alloc(24);
  box.writeUInt32BE(box.length);
  box.write('ftyp', 4, 'latin1');
  box.write(brand, 8, 'latin1');
  box.write('isom', 16, 'latin1');
  box.write('mp42', 20, 'latin1');
  return box;
}
